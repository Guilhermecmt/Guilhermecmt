def typing(phrases: list[str], x: float, y: float, size: float, color: str, period=4.5) -> str:
    """Frases que se digitam e se apagam em ciclo. textLength fixa a largura de cada letra,
    então o recorte e o cursor andam um caractere por vez em qualquer fonte monoespaçada."""
    cw = size * MONO_W
    total = period * len(phrases)
    out = []
    for i, ph in enumerate(phrases):
        n = len(ph)
        start = i * period
        type_dt, erase_dt = 0.055, 0.018
        times, widths = [0.0], [0.0]
        for k in range(1, n + 1):
            times.append(start + 0.35 + k * type_dt); widths.append(k * cw)
        hold_end = start + period - 0.25 - n * erase_dt
        for k in range(n - 1, -1, -1):
            times.append(hold_end + (n - k) * erase_dt); widths.append(k * cw)
        kt = ";".join(f"{min(tt / total, 1):.5f}" for tt in times)
        vals = ";".join(f"{w:.1f}" for w in widths)
        xs = ";".join(f"{x + w:.1f}" for w in widths)
        cid = f"tp{i}"
        out.append(
            f'<clipPath id="{cid}"><rect x="{x}" y="{y - size}" height="{size * 1.5}" width="0">'
            f'<animate attributeName="width" values="{vals}" keyTimes="{kt}" calcMode="discrete" dur="{total}s" repeatCount="indefinite"/>'
            f'</rect></clipPath>'
            f'<text x="{x}" y="{y}" clip-path="url(#{cid})" font-family="{MONO}" font-size="{size}" fill="{color}" '
            f'textLength="{n * cw:.1f}" lengthAdjust="spacingAndGlyphs">{e(ph)}</text>'
        )
        # cursor desta frase: só aparece durante a vez dela
        vis_kt = f"0;{start / total:.5f};{(start + period) / total:.5f}"
        out.append(
            f'<rect x="{x}" y="{y - size * 0.82:.1f}" width="{size * 0.5:.1f}" height="{size * 1.02:.1f}" fill="{color}" opacity="0">'
            f'<animate attributeName="x" values="{xs}" keyTimes="{kt}" calcMode="discrete" dur="{total}s" repeatCount="indefinite"/>'
            f'<animate attributeName="opacity" values="0;0.85;0" keyTimes="{vis_kt}" calcMode="discrete" dur="{total}s" repeatCount="indefinite"/>'
            f'</rect>'
        )
    return "\n".join(out)


