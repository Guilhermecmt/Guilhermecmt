def make_thumbs() -> None:
    from PIL import Image, ImageFilter

    THUMBS.mkdir(parents=True, exist_ok=True)
    tw, th = 960, 440
    for p in PROJECTS:
        src = PORTFOLIO / p["slug"] / "capa.webp"
        im = Image.open(src).convert("RGB")
        if p.get("contain"):
            # capa em retrato: fundo desfocado da própria imagem e a imagem inteira por cima
            bg = im.resize((tw, int(im.height * tw / im.width))).crop((0, 0, tw, th))
            bg = bg.filter(ImageFilter.GaussianBlur(28)).point(lambda v: int(v * 0.55))
            fg = im.copy()
            fg.thumbnail((tw, int(th * 1.6)))
            fg = fg.crop((0, 0, fg.width, min(fg.height, th - 40)))
            bg.paste(fg, ((tw - fg.width) // 2, 40))
            out = bg
        else:
            scale = max(tw / im.width, th / im.height)
            im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
            x = (im.width - tw) // 2
            y = round((im.height - th) * p["focus"])
            out = im.crop((x, y, x + tw, y + th))
        out.save(THUMBS / f"{p['slug']}.jpg", quality=80, optimize=True, progressive=True)
        print("thumb", p["slug"])


def thumb_uri(slug: str) -> str:
    data = (THUMBS / f"{slug}.jpg").read_bytes()
    return "data:image/jpeg;base64," + base64.b64encode(data).decode()


# ---------------------------------------------------------------- peças comuns

def e(s: str) -> str:
    return escape(s, quote=True)


def pill(x: float, y: float, label: str, color: str, pulse: bool, size=13, dark_glass=True, t=None) -> str:
    """Etiqueta de status com um ponto que pulsa (SMIL, funciona dentro de <img>)."""
    w = len(label) * size * MONO_W + 44
    h = size + 16
    fill = "#000000" if dark_glass else t["chip"]
    fill_op = 0.55 if dark_glass else 1
    txt = "#ffffff" if dark_glass else t["text"]
    cx, cy = x + 16, y + h / 2
    ring = (
        f'<circle cx="{cx}" cy="{cy}" r="4" fill="{color}">'
        f'<animate attributeName="r" values="4;11" dur="2s" repeatCount="indefinite"/>'
        f'<animate attributeName="opacity" values="0.7;0" dur="2s" repeatCount="indefinite"/></circle>'
        if pulse else ""
    )
    stroke = "" if dark_glass else f' stroke="{t["border"]}"'
    return (
        f'<g><rect x="{x}" y="{y}" width="{w:.0f}" height="{h}" rx="{h/2}" fill="{fill}" fill-opacity="{fill_op}"{stroke}/>'
        f'{ring}<circle cx="{cx}" cy="{cy}" r="4" fill="{color}"/>'
        f'<text x="{x + 28}" y="{cy + size*0.36:.1f}" font-family="{MONO}" font-size="{size}" '
        f'font-weight="600" letter-spacing="0.5" fill="{txt}">{e(label)}</text></g>'
    )


def svg_open(w: int, h: int, label: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'role="img" aria-label="{e(label)}">')


